function leaderUrl(id) {
  return "leader.html?id=" + encodeURIComponent(id);
}

function formatVotes(n) {
  if (n >= 1000000) return (n / 1000000).toFixed(2) + "M";
  if (n >= 1000) return n.toLocaleString("en-US");
  return String(n);
}

